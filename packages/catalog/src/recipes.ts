import type { FoodState, IngredientRole } from "@nutriduo/domain";

/**
 * Recetario base de NutriDuo. Recetas caseras de elaboración propia, con
 * gramos POR PORCIÓN en el estado en que se pesan. Sin pescados, mariscos,
 * cerdo, pavo ni quinoa.
 *
 * Roles: "adjustable" (el motor la mueve), "side" (acompañamiento: se cocina
 * aparte y cada uno puede omitirlo), "ratio" (se mueve en bloque con su
 * grupo, p. ej. un aliño), "fixed" (no cambia: sal, especias).
 *
 * Las etiquetas vegetariana / sin lactosa / sin gluten / alta en proteínas /
 * rápida se calculan a partir de los ingredientes (ver tags.ts).
 */
export interface CatalogRecipeLine {
  ingredient: string;
  grams: number;
  state?: FoodState;
  role: IngredientRole;
  minG?: number;
  maxG?: number;
  ratioGroup?: string;
  integerUnitG?: number;
}

export interface CatalogRecipeDef {
  slug: string;
  name: string;
  category: "desayunos" | "almuerzos" | "cenas" | "snacks" | "postres" | "preparaciones_base";
  prepMinutes: number;
  servings: number;
  homogeneous: boolean;
  /** Peso cocido total esperado (todas las porciones) cuando el cálculo por rendimientos no aplica (líquidos, masas). */
  expectedCookedYieldG?: number;
  tags: string[];
  lines: CatalogRecipeLine[];
  instructions: string;
}

